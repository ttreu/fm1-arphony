#!/usr/bin/env python3
"""Write app/arp_forbidden.inc: fingerprints of every 7-note figure (as
intervals, any key) in the reference recordings. The firmware never plays a
RANDOM riff that contains one of them.

    python3 tools/make_forbidden.py ../examples
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'tests'))
import riff_similarity as rs  # noqa: E402


def main():
    refs = rs.references(sys.argv[1])
    prints = set()
    for notes in refs.values():
        for w in rs.windows(notes):
            prints.add(rs.fingerprint(w))
            prints.add(rs.fingerprint(tuple(-d for d in w)))  # the same figure upside down
    values = sorted(prints)
    lines = ['/* Generated by tools/make_forbidden.py from the reference recordings: FNV-1a',
             f' * fingerprints of their 7-note figures (as intervals, any key, also inverted). {len(values)} entries. */',
             'static const uint32_t forbidden[] = {']
    for i in range(0, len(values), 6):
        lines.append('    ' + ', '.join(f'0x{v:08x}U' for v in values[i:i + 6]) + ',')
    lines.append('};')
    out = Path(__file__).resolve().parent.parent / 'app/arp_forbidden.inc'
    out.write_text('\n'.join(lines) + '\n')
    print(f'{len(values)} fingerprints -> {out}')


if __name__ == '__main__':
    main()
